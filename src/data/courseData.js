export const getProgressPercentage=(user)=>{

  var totalWeight=0;
  var totalUserProgress=0;

  for(let i=0;i<modules.length;i++){
    totalWeight+=modules[i].lessons.length;
    totalUserProgress+=user.moduleProgress[i];
  }
  totalWeight+=user.assignmentsDone+user.assignmentsLeft;
  totalUserProgress+=user.assignmentsDone;

  totalWeight+=quizData.length;
  totalUserProgress+=user.quizAttempted.length;

  totalWeight+=projects.length;
  totalUserProgress+=user.projectsCompleted.length;
  
  return (totalUserProgress*100/totalWeight).toFixed(2);
}

